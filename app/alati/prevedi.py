def escape(t):
    return t.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def write(path, prevodi, identitet=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    linije = [
        "/* Generisano skriptom app/alati/prevedi.py — ne uređivati ručno. */",
        "",
    ]
    for k in sorted(prevodi):
        v = k if identitet else prevodi[k]
        linije.append('"%s" = "%s";' % (escape(k), escape(v)))
    open(path, "w", encoding="utf-8").write("\n".join(linije) + "\n")

